@pytest.mark.django_db
def test_registration_partial_unique_blocks_duplicate_active():
    from events.models import RegStatus
    from events.tests.factories import EventFactory, RegistrationFactory

    user = UserFactory()
    event = EventFactory()
    RegistrationFactory(event=event, user=user, status=RegStatus.CONFIRMED)
    with pytest.raises(IntegrityError):
        RegistrationFactory(event=event, user=user, status=RegStatus.CONFIRMED)


@pytest.mark.django_db
def test_registration_partial_unique_allows_canceled_then_new():
    """A canceled registration should not block a new active one."""
    from events.models import RegStatus
    from events.tests.factories import EventFactory, RegistrationFactory

    user = UserFactory()
    event = EventFactory()
    RegistrationFactory(event=event, user=user, status=RegStatus.CANCELED)
    # Should not raise
    reg2 = RegistrationFactory(event=event, user=user, status=RegStatus.CONFIRMED)
    assert reg2.pk is not None


