@pytest.mark.django_db
def test_event_slug_autogenerated():
    from events.tests.factories import EventFactory

    event = EventFactory(title="Mroczna Głębia")
    assert event.slug == "mroczna-glebia"


@pytest.mark.django_db
def test_event_slug_collision_suffix():
    from events.tests.factories import EventFactory

    e1 = EventFactory(title="Ciemny Tunel")
    e2 = EventFactory(title="Ciemny Tunel")
    assert e1.slug != e2.slug
    assert e2.slug.startswith("ciemny-tunel")


@pytest.mark.django_db
def test_event_is_free_derived_from_price():
    from events.tests.factories import EventFactory

    free_event = EventFactory(price_pln=0)
    paid_event = EventFactory(price_pln=50)
    assert free_event.is_free is True
    assert paid_event.is_free is False


@pytest.mark.django_db
def test_event_base_manager_all_objects():
    from events.models import Event
    from events.tests.factories import EventFactory

    event = EventFactory()
    event.delete()  # soft-delete
    # objects (default) should not see it
    assert Event.objects.filter(pk=event.pk).count() == 0
    # all_objects should see it
    assert Event.all_objects.filter(pk=event.pk).count() == 1


@pytest.mark.django_db
def test_event_soft_delete():
    from events.models import Event
    from events.tests.factories import EventFactory

    event = EventFactory()
    pk = event.pk
    event.delete()
    obj = Event.all_objects.get(pk=pk)
    assert obj.is_deleted is True
    assert obj.deleted_at is not None


